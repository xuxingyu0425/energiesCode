"""Plot aggregate results and optionally select examples from the WTBD images."""
import argparse
from pathlib import Path
import os
import subprocess
import sys
from common import ROOT

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image-root",type=Path,help="WTBD JPEGImages folder; enables example Figure 4 without redistributing source photos")
    parser.add_argument("--annotation-audit", type=Path, required=True,
                        help="dual_annotation_audit.csv generated by tools/prepare_data.py")
    args=parser.parse_args()
    os.environ.setdefault("MPLBACKEND","Agg")
    (ROOT/"outputs/figures").mkdir(parents=True,exist_ok=True)
    (ROOT/"outputs/figure_qa").mkdir(parents=True,exist_ok=True)
    subprocess.run([sys.executable, str(ROOT/"tools/fig2_original.py"),
                    "--annotation-audit", str(args.annotation_audit.resolve())], check=True)
    import figures_original
    figures_original.fig3();figures_original.fig5()
    if args.image_root:
        if not args.image_root.is_dir():raise FileNotFoundError(args.image_root)
        os.environ["WTBD_IMAGE_DIR"]=str(args.image_root.resolve())
        figures_original.fig4()
    print("Figures saved to outputs/figures/. Figure 1 is an authored architecture schematic, not a numerical plot.")

if __name__=="__main__":main()
