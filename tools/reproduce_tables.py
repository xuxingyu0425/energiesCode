"""Recalculate aggregate tables from per-seed results.

Unadjusted paired t intervals quantify training variability on the fixed split."""
import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from common import ROOT, CELLS, read_csv, load_json, interval, summary, save_csv

def paired(frame, grouping, metrics):
    rows=[]
    for key,part in frame.groupby(grouping,sort=False):
        if not isinstance(key,tuple): key=(key,)
        base=part.loc[part["cell"]=="A"].set_index("seed")
        for cell in CELLS[1:]:
            candidate=part.loc[part["cell"]==cell].set_index("seed")
            if candidate.empty:continue
            seeds=base.index.intersection(candidate.index).sort_values()
            assert len(seeds)==5
            for metric in metrics:
                rows.append(dict(zip(grouping,key),cell=cell,metric=metric,
                                 **interval(candidate.loc[seeds,metric]-base.loc[seeds,metric])))
    return pd.DataFrame(rows)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path,default=ROOT/"outputs/tables")
    parser.add_argument("--annotation-audit", type=Path, required=True,
                        help="dual_annotation_audit.csv generated by tools/prepare_data.py")
    args=parser.parse_args(); out=args.output; out.mkdir(parents=True,exist_ok=True)
    # Tables 1--4 are supervision definitions and dataset metadata, not model scores.
    strategies=pd.DataFrame([
        dict(strategy="A",assignment="A",regression="A",classification="A"),
        dict(strategy="B",assignment="B",regression="B",classification="B"),
        dict(strategy="S1",assignment="coordinate average",regression="coordinate average",classification="A on conflicts"),
        dict(strategy="S2",assignment="coordinate average",regression="equal mean of losses against A and B",classification="A on conflicts")])
    save_csv(strategies,out,"table01_supervision_definitions.csv")
    annotation=pd.read_csv(args.annotation_audit)
    coordinates=np.asarray([list(map(float,s.split())) for s in annotation["box_a"]])
    widths=coordinates[:,2]-coordinates[:,0];heights=coordinates[:,3]-coordinates[:,1]
    annotation["elongated_A"]=np.maximum(widths/heights,heights/widths)>=3
    classes=["craze","crack","corrosion","hide_craze","surface_injure","thunderstrike"]
    english=["Crazing","Cracks","Corrosion","Hidden crazing","Surface damage","Lightning damage"]
    rows=[]
    for cls,name in zip(classes,english):
        a=annotation.loc[annotation["class_a"]==cls]
        rows.append(dict(dataset_label=cls,english_name=name,A_boxes=len(a),A_share_percent=100*len(a)/len(annotation),
                         B_boxes=int((annotation["class_b"]==cls).sum()),elongated_A_percent=100*a["elongated_A"].mean()))
    rows.append(dict(dataset_label="Total",english_name="",A_boxes=len(annotation),A_share_percent=100.,
                     B_boxes=int(annotation["class_b"].notna().sum()),elongated_A_percent=100*annotation["elongated_A"].mean()))
    save_csv(pd.DataFrame(rows),out,"table02_class_distribution.csv")
    split=read_csv("split_manifest.csv"); joined=annotation.merge(split[["image","split"]],on="image",validate="many_to_one")
    rows=[]
    for subset in ["train","val","test"]:
        part=joined.loc[joined["split"]==subset]
        rows.append(dict(subset=subset,images=int((split["split"]==subset).sum()),A_boxes=len(part),B_boxes=int(part["class_b"].notna().sum())))
    save_csv(pd.DataFrame(rows),out,"table03_partition.csv")
    save_csv(pd.DataFrame(load_json(ROOT/"data/file_inventory.json")["inventory"]),out,"table04_dataset_files.csv")
    ap=read_csv("yolov8_reeval_table.csv");ap=ap.loc[ap["gt"]=="annotator_a"]
    assert len(ap)==80
    save_csv(summary(ap,["cell","ck"],["AP50","AP75","AP"]),out,"table05_detection.csv")
    save_csv(paired(ap,["ck"],["AP50","AP75","AP"]),out,"table06_detection_differences.csv")
    loc=read_csv("localization_v12.csv");common=read_csv("common_tp_v12.csv"); rows=[]
    for (cell,ck),part in loc.groupby(["cell","ck"],sort=False):
        matched=common.loc[(common["cell"]==cell)&(common["ck"]==ck)]
        row=dict(cell=cell,ck=ck,tp_mean_iou_mean=part["tp_mean_iou"].mean(),
                 tp_mean_iou_sample_sd=part["tp_mean_iou"].std(ddof=1),
                 coverage75_mean=part["gt_iou75"].mean(),
                 coverage75_sample_sd=part["gt_iou75"].std(ddof=1))
        if cell!="A":row.update(n_common_mean=matched["n_common"].mean(),
                                n_common_min=matched["n_common"].min(),
                                n_common_max=matched["n_common"].max(),
                                **interval(matched["mean_delta_iou"]))
        rows.append(row)
    save_csv(pd.DataFrame(rows),out,"table07_localization.csv")
    rows=[]
    for ck in ["best","last"]:
        part=ap.loc[ap["ck"]==ck].set_index(["cell","seed"])
        for comparator in ["A","S1"]:
            rows.append(dict(checkpoint=ck,comparison="S2-"+comparator,
                             **interval(part.loc["S2","AP"]-part.loc[comparator,"AP"])))
    save_csv(pd.DataFrame(rows),out,"table08_supervision.csv")
    increments=read_csv("cbam_increment_per_seed_v16.csv");rows=[]
    for (ck,metric),part in increments.groupby(["checkpoint","metric"],sort=False):
        rows.append(dict(checkpoint=ck,metric=metric,**interval(part["difference"])))
    save_csv(pd.DataFrame(rows),out,"table09_cbam_increment.csv")
    locked=read_csv("locked_per_seed.csv")
    save_csv(summary(locked,["cell"],["P","R","F1","FP","FN"]),out,"table10_locked_screening.csv")
    locked["checkpoint"]="last_locked"
    save_csv(paired(locked,["checkpoint"],["P","R","F1","FP","FN"]),out,"table11_screening_differences.csv")
    fixed=read_csv("screening_per_seed.csv");fixed=fixed.loc[fixed["cell"].isin(["A","A_ESB","S2_CBAM"])]
    save_csv(summary(fixed,["threshold","cell"],["P","R","F1","FP","FN"]),out,"table12_fixed_thresholds.csv")
    sensitivity=read_csv("annotation_sensitivity.csv")
    sensitivity=sensitivity.loc[sensitivity["protocol"]=="last_val_locked"]
    save_csv(summary(sensitivity,["cell","truth"],["P","R","F1","FP","FN"]),out,"table13_annotation_sensitivity.csv")
    cost=read_csv("model_complexity.csv");latency=load_json(ROOT/"data/latency_unified.json");rows=[]
    baseline=latency["v8_none"]["params"]
    for module,method in [("none","f0_baseline"),("esb","f1_esb"),("cbam","cbam")]:
        record=latency["v8_"+module];c=cost.loc[cost["method"]==method].iloc[0]
        assert int(c["parameters"])==record["params"]
        rows.append(dict(module=module,parameters=record["params"],
                         parameter_increase_percent=100*(record["params"]-baseline)/baseline,
                         gflops_estimate=c["gflops_estimate"],forward_latency_ms=record["ms"],
                         input_size=768,precision="FP32",batch=1,timing_rounds=3))
    save_csv(pd.DataFrame(rows),out,"table14_model_cost.csv")
    # Check the rounded summary values against the per-seed results.
    endpoint=ap.loc[(ap["ck"]=="last")&(ap["cell"]=="S2_CBAM"),"AP"].mean()
    assert round(endpoint,2)==40.26
    f1=locked.loc[locked["cell"]=="S2_CBAM","F1"].mean()
    assert round(f1,2)==75.17
    report=dict(tables_generated=list(range(1,15)),AP50_95_S2_CBAM_epoch200=endpoint,
                F1_S2_CBAM_locked=f1,inference_performed=False,training_performed=False,
                source="archived original-study per-seed outputs",confidence_intervals="paired Student t; n=5; df=4; unadjusted")
    (out/"verification.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    print(json.dumps(report,indent=2))

if __name__=="__main__":main()
